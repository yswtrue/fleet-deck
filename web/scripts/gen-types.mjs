// Generates TypeScript types from the FleetDeck protocol JSON Schema.
//
// The exported schema is a draft 2020-12 document whose root is `type: object`
// with an empty `properties` map; every named type lives under `$defs`. The
// plain `json2ts` CLI therefore emits an empty root interface and drops the
// definitions. To get one top-level interface per `$defs` entry we drive the
// `json-schema-to-typescript` Node API directly: we synthesize root properties
// that `$ref` every definition, so the compiler resolves and emits them all as
// named interfaces.
import { compile } from 'json-schema-to-typescript'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const webDir = resolve(here, '..')
const protocolDir = resolve(webDir, 'src/gen/protocol')
const schemaPath = resolve(protocolDir, 'protocol.schema.json')
const outPath = resolve(protocolDir, 'index.ts')

const schema = JSON.parse(readFileSync(schemaPath, 'utf8'))
const defs = schema.$defs ?? schema.definitions ?? {}
const names = Object.keys(defs)

if (names.length === 0) {
  throw new Error(`no $defs found in ${schemaPath}`)
}

const root = {
  ...schema,
  $defs: defs,
  definitions: defs,
  properties: Object.fromEntries(
    names.map((name) => [name, { $ref: `#/$defs/${name}` }]),
  ),
}

const ts = await compile(root, 'ProtocolSchema', {
  bannerComment: `/* eslint-disable */
/**
 * This file was automatically generated by json-schema-to-typescript.
 * DO NOT MODIFY IT BY HAND. Instead, run \`pnpm run gen:types\`.
 */`,
  additionalProperties: false,
  cwd: protocolDir,
})

writeFileSync(outPath, ts)
console.log(`generated ${names.length} definitions -> ${outPath}`)
